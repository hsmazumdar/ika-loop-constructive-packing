"""CS3 - sliding-tile puzzles (Expt 23, DESIGN.md section 4). Environment + reference solvers only (REFERENCE: BFS-optimal, A* with Manhattan).

State = tuple of length R*C, 0 = blank, goal = (1, 2, ..., R*C-1, 0). A task = (R, C, start state, node budget).
Splits: train = boards 2x3, 3x3 (scramble depth 5-30); test_iid = same boards, new scrambles; test_deep = same boards, depth 31-80;
test_size = unseen boards 2x4, 3x4 (and 4x4 with a node budget); deterministic from (split, index).
No heuristic enters a learner; Manhattan appears only in `astar` (reference)."""
from __future__ import annotations

import heapq
from collections import deque

import numpy as np

TRAIN_BOARDS = [(2, 3), (3, 3)]
TEST_BOARDS = [(2, 4), (3, 4), (4, 4)]
SEED_BASE = {"train": 11_000_000, "dev": 12_000_000, "test_iid": 13_000_000, "test_deep": 14_000_000, "test_size": 15_000_000}


def goal(R, C):
    return tuple(list(range(1, R * C)) + [0])


def neighbours_idx(R, C):
    nb = []
    for i in range(R * C):
        r, c = divmod(i, C)
        nb.append([rr * C + cc for rr, cc in ((r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)) if 0 <= rr < R and 0 <= cc < C])
    return nb


_NB = {}


def moves(state, R, C):
    """Successor states (blank swapped with each neighbour). Returns list of (next_state, tile_moved)."""
    nb = _NB.setdefault((R, C), neighbours_idx(R, C))
    z = state.index(0)
    out = []
    for j in nb[z]:
        s = list(state); s[z], s[j] = s[j], 0
        out.append((tuple(s), state[j]))
    return out


def scramble(R, C, depth, rng):
    s, prev = goal(R, C), None
    for _ in range(depth):
        nxt = [m for m in moves(s, R, C) if m[0] != prev]
        prev, s = s, nxt[int(rng.integers(len(nxt)))][0]
    return s


def make_task(split: str, index: int):
    rng = np.random.default_rng((SEED_BASE[split], index))
    if split == "test_size":
        R, C = TEST_BOARDS[int(rng.integers(len(TEST_BOARDS)))]
        depth = int(rng.integers(10, 41))
    else:
        R, C = TRAIN_BOARDS[int(rng.integers(len(TRAIN_BOARDS)))]
        depth = int(rng.integers(31, 81)) if split == "test_deep" else int(rng.integers(5, 31))
    return {"id": f"{split}_{index:05d}", "split": split, "R": R, "C": C, "start": scramble(R, C, depth, rng), "scramble_depth": depth}


_BFS = {}


def bfs_table(R, C):
    """Exact distance-to-goal for every reachable state (2x3: 360, 2x4: 20,160, 3x3: 181,440). Not feasible for 3x4 / 4x4."""
    k = (R, C)
    if k not in _BFS:
        g = goal(R, C); d = {g: 0}; q = deque([g])
        while q:
            s = q.popleft()
            for t, _ in moves(s, R, C):
                if t not in d:
                    d[t] = d[s] + 1; q.append(t)
        _BFS[k] = d
    return _BFS[k]


def optimal_length(task):
    if task["R"] * task["C"] <= 9 or (task["R"], task["C"]) == (2, 4):
        return bfs_table(task["R"], task["C"])[task["start"]]
    return None


def manhattan(state, R, C):
    tot = 0
    for i, v in enumerate(state):
        if v:
            g = v - 1
            tot += abs(i // C - g // C) + abs(i % C - g % C)
    return tot


def astar(start, R, C, node_budget=200_000, weight=1.0):
    """A* with the Manhattan heuristic (REFERENCE ONLY). weight>1 = weighted A* (faster, suboptimal). Returns (path_len or None, expansions)."""
    g0 = goal(R, C)
    openq = [(weight * manhattan(start, R, C), 0, start)]
    best = {start: 0}
    exp = 0
    while openq and exp < node_budget:
        f, g, s = heapq.heappop(openq)
        if s == g0:
            return g, exp
        if g > best.get(s, 1 << 30):
            continue
        exp += 1
        for t, _ in moves(s, R, C):
            ng = g + 1
            if ng < best.get(t, 1 << 30):
                best[t] = ng
                heapq.heappush(openq, (ng + weight * manhattan(t, R, C), ng, t))
    return None, exp


def random_walk_solver(start, R, C, node_budget, rng):
    """Uniform random walk with no backtracking, up to node_budget steps: the 'random generation' reference. Returns steps or None."""
    g0 = goal(R, C); s, prev = start, None
    for n in range(node_budget):
        if s == g0:
            return n
        nxt = [m for m in moves(s, R, C) if m[0] != prev]
        prev, s = s, nxt[int(rng.integers(len(nxt)))][0]
    return n if s == g0 else None


